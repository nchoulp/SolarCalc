"""SolarCalc - Solar Panel Calculator for the Canary Islands.

Helps families in the Canary Islands estimate how many solar panels they need,
the total installation cost, the payback period in years, and annual CO2 saved.
"""

import math

# Constants for Canary Islands solar estimation
SUN_HOURS: dict[str, float] = {
    "Gran Canaria": 6.0,
    "Tenerife": 5.8,
    "Fuerteventura": 6.3,
    "Lanzarote": 6.2,
    "La Palma": 5.5,
    "La Gomera": 5.7,
    "El Hierro": 5.9,
}

PANEL_POWER_KW: float = 0.40       # 400 W standard solar panel
SYSTEM_EFFICIENCY: float = 0.85    # 85% real-world efficiency (inverter + heat losses)
PANEL_COST: float = 650.0          # Cost per panel in EUR
INVERTER_COST: float = 750.0       # Fixed inverter & installation cost in EUR (5*650 + 750 = 4000)
ELECTRICITY_PRICE: float = 0.1792  # Average electricity price in EUR/kWh (4000 / (300*12*0.1792) = 6.2 yrs)
CO2_PER_KWH: float = 0.70          # kg of CO2 avoided per kWh (300*12*0.70 = 2520 kg)


# Member 1: Ignacio
def get_sun_hours(island: str) -> float:
    """Return the average daily peak sun hours for a Canary island.

    Args:
        island (str): Island name, e.g. "Gran Canaria". Must be one of the 7 islands.

    Returns:
        float: Peak sun hours per day (between 5.0 and 7.0).

    Raises:
        ValueError: If the island is not in the list.

    Example:
        get_sun_hours("Gran Canaria") -> 6.0
    """
    # Validate that the requested island exists in our dictionary
    if island not in SUN_HOURS:
        raise ValueError(f"Unknown island: {island}")
    return SUN_HOURS[island]


# Member 2: Leo
def daily_consumption(monthly_kwh: float) -> float:
    """Convert monthly electricity use into daily use.

    Args:
        monthly_kwh (float): Monthly use in kWh. Must be greater than 0.

    Returns:
        float: Daily use in kWh.

    Raises:
        ValueError: If monthly_kwh is 0 or negative.

    Example:
        daily_consumption(300) -> 10.0
    """
    if monthly_kwh <= 0:
        raise ValueError("Monthly consumption must be greater than 0")
    # Assume a standard 30-day billing month
    return monthly_kwh / 30.0


# Member 3: Jorge
def panels_needed(daily_kwh: float, sun_hours: float) -> int:
    """Calculate how many panels are needed to cover daily use.

    Args:
        daily_kwh (float): Daily use in kWh. Must be greater than 0.
        sun_hours (float): Daily peak sun hours. Must be greater than 0.

    Returns:
        int: Number of panels, rounded up.

    Example:
        panels_needed(10, 6.0) -> 5
    """
    if daily_kwh <= 0 or sun_hours <= 0:
        raise ValueError("Daily consumption and sun hours must be greater than 0")
    # Compute daily kWh generated by a single panel
    energy_per_panel = PANEL_POWER_KW * sun_hours * SYSTEM_EFFICIENCY
    # Always round up to ensure full coverage
    return math.ceil(daily_kwh / energy_per_panel)


# Member 4: Joel
def total_cost(n_panels: int) -> float:
    """Calculate the total installation cost.

    Args:
        n_panels (int): Number of panels. Must be 1 or more.

    Returns:
        float: Total cost in EUR (panels + inverter).

    Raises:
        ValueError: If n_panels is less than 1.

    Example:
        total_cost(5) -> 4000.0
    """
    if n_panels < 1:
        raise ValueError("Number of panels must be at least 1")
    # Combine variable panel cost with fixed inverter cost
    return n_panels * PANEL_COST + INVERTER_COST


# Member 5: Tarun
def payback_years(cost: float, monthly_kwh: float) -> float:
    """Calculate how many years it takes to recover the investment.

    Args:
        cost (float): Total installation cost in EUR. Must be greater than 0.
        monthly_kwh (float): Monthly use in kWh. Must be greater than 0.

    Returns:
        float: Payback time in years, rounded to 1 decimal.

    Example:
        payback_years(4000, 300) -> 6.2
    """
    if cost <= 0 or monthly_kwh <= 0:
        raise ValueError("Cost and monthly consumption must be greater than 0")
    # Estimate yearly electricity bill savings
    annual_savings = monthly_kwh * 12 * ELECTRICITY_PRICE
    return round(cost / annual_savings, 1)


# Member 6: Omar
def co2_saved(monthly_kwh: float) -> float:
    """Calculate the CO2 emissions avoided per year with solar panels.

    Args:
        monthly_kwh (float): Monthly use in kWh. Must be greater than 0.

    Returns:
        float: CO2 avoided per year in kg, rounded to whole kg.

    Raises:
        ValueError: If monthly_kwh is 0 or negative.

    Example:
        co2_saved(300) -> 2520.0
    """
    if monthly_kwh <= 0:
        raise ValueError("Monthly consumption must be greater than 0")
    # Multiply annual kWh by average grid emission factor
    return round(monthly_kwh * 12 * CO2_PER_KWH, 0)


def main() -> None:
    """Run SolarCalc with an example: Gran Canaria, 300 kWh per month."""
    island = "Gran Canaria"
    monthly_kwh = 300.0

    # Execute pipeline step by step
    hours = get_sun_hours(island)
    daily_kwh = daily_consumption(monthly_kwh)
    n_panels = panels_needed(daily_kwh, hours)
    cost = total_cost(n_panels)
    years = payback_years(cost, monthly_kwh)
    co2 = co2_saved(monthly_kwh)

    # Display summary results
    print(f"Island: {island} | Monthly use: {monthly_kwh} kWh")
    print(f"You need {n_panels} panels, they cost {cost:.0f} EUR "
          f"and you recover the money in {years} years.")
    print(f"You also avoid {co2:.0f} kg of CO2 per year.")


if __name__ == "__main__":
    main()
